# Arithmetic Operations
a = 10
b = 5

print("Addition:", a + b) # Addition
print("Subtraction:", a - b) # Subtraction
print("Multiplication:", a * b) # Multiplication
print("Division:", a / b) # Division


#Relational Operations
a = 10
b = 5

print("Equal to:", a == b) # Equal to
print("Not equal to:", a != b) # Not equal to
print("Greater than:", a > b) # Greater than
print("Less than:", a < b) # Less than
print("Greater than or equal to:", a >= b) # Greater than or equal to
print("Less than or equal to:", a <= b) # Less than or equal to

# Logical Operations
a = True
b = False

print("AND:", a and b) # AND
print("OR:", a or b) # OR
print("NOT:", not a) # NOT

# Assignment Operations
a += b # a = a + b
print("Addition Assignment:", a) # Addition Assignment
a -= b # a = a - b
print("Subtraction Assignment:", a) # Subtraction Assignment
a *= b # a = a * b
print("Multiplication Assignment:", a) # Multiplication Assignment

